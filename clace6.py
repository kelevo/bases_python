# Operadores inversos
a = 10
b = 3
print('Suma:', a + b)
print('Resta:', a - b)
print('Multiplicacion:', a * b)
print('Division:', a / b)

print('Modulo:', a % b)
print('Parte entera de la division:', a // b)
print('Potencia:', a ** b)

a += 2
b -= 1
print('Nuevo valor de a:', a)
print('Nuevo valor de b:', b)

operacion_1 = 2 + 3 * 4
operacion_2 = (2 + 3) * 4
print('Resultado de la operacion:', operacion_1)
print('Resultado de la operacion:', operacion_2)

